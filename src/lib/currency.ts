export type CurrencyCode = (typeof RAW_CURRENCIES)[number][0];

export interface CurrencyConfig {
  code: CurrencyCode;
  symbol: string;
  name: string;
  label: string;
  zeroDecimal: boolean;
}

export const CURRENCY_LIST: CurrencyConfig[] = RAW_CURRENCIES.map(
  ([code, symbol, name, zd]) => ({
    code,
    symbol,
    name,
    label: symbol !== code ? `${code} (${symbol} · ${name})` : `${code} (${name})`,
    zeroDecimal: zd === 1,
  })
);

export const CURRENCIES: Record<CurrencyCode, CurrencyConfig> = Object.fromEntries(
  CURRENCY_LIST.map((cfg) => [cfg.code, cfg])
) as Record<CurrencyCode, CurrencyConfig>;

export function formatMoney(
  amount: number,
  currency: CurrencyCode = "USD",
  decimals = 0
): string {
  const cfg = CURRENCIES[currency] ?? CURRENCIES.USD;
  const maxFractionDigits = cfg.zeroDecimal ? 0 : decimals;
  const sign = amount < 0 ? "-" : "";
  const formatted = new Intl.NumberFormat("en-US", {
    minimumFractionDigits: maxFractionDigits,
    maximumFractionDigits: maxFractionDigits,
  }).format(Math.abs(amount));

  const needsSpace = /[A-Za-z.]$/.test(cfg.symbol);
  return needsSpace
    ? `${sign}${cfg.symbol} ${formatted}`
    : `${sign}${cfg.symbol}${formatted}`;
}
